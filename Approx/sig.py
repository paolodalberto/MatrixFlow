def faie(x,p):
    #tmpx = x
    tmpx = numpy.minimum(4.1, x)
    tmpx = numpy.maximum(-4.1,tmpx)
    tmpx_abs = numpy.absolute(tmpx)

    return p[0] + p[1]*tmpx - p[2]*tmpx_abs*tmpx

def F(x,p):
    
    xx = x.astype(numpy.float64)
    r = xx*0.0 + p[0]
    for i in range(1,p.size):
        r += p[i]*xx**i
    return r


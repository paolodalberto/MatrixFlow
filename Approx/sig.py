def C(p,x,y,cost_function = cost, method='powell'):
    
    res = scipy.optimize.minimize(cost_function,
                                  p,
                                  args=(x,y),
                                  method=method,
                                  #bounds=((p[0]/10,p[0]),(p[1]/10,p[1]),(p[2]/10,p[2])),
                                  options={ 'disp': True})

    return res




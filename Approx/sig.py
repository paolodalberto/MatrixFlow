def aie(x):
    tmpx = numpy.minimum(4,x)
    tmpx = numpy.maximum(-4,tmpx)
    tmpx_abs = numpy.absolute(tmpx)

    return (1/2) + (1/4)*tmpx - (1/32)*tmpx_abs*tmpx

